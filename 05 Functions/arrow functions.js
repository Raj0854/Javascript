// arrow function
// arrow functions are a shorter syntax for writing function expressions
// they are anonymous functions that can be assigned to a variable
const functionName = () => { // code to be executed 
    };
// arrow function with parameters
const functionName = (parameter1, parameter2) => {
    // code to be executed
};
// arrow function with return value
const functionName = (parameter1, parameter2) => {
    // code to be executed
    return parameter1 + parameter2;
};
// arrow function with implicit return value
// if the function body contains only one expression, we can omit the curly braces and the return keyword
const functionName = (parameter1, parameter2) => parameter1 + parameter2;