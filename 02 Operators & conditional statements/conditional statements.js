// Conditional Statements are used to perform different actions based on different conditions. In JavaScript, we have several types of conditional statements, including if, else if, else, switch, and ternary operator.

// 1. if statement
let temperature = 25;
if (temperature > 20) {
    console.log("It's a nice day!");
}

// 2. if...else statement
let time = 10;
if (time < 12) {
    console.log("Good morning!");
} else {
    console.log("Good afternoon!");
}

// 3. if...else if...else statement
let score = 85;
if (score >= 90) {
    console.log("Grade: A");
}
else if (score >= 80) {
    console.log("Grade: B");
}
else if (score >= 70) {
    console.log("Grade: C");
}
else if (score >= 60) {
    console.log("Grade: D");
}
else {
    console.log("Grade: F");
}

